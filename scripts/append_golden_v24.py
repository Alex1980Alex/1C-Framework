def main():
    data = json.loads(PATH.read_text(encoding="utf-8"))
    all_new = bsl_v4_items() + wiki_items() + graph_items()
    existing_ids = {it["id"] for it in data["items"]}
    added = 0
    for item in all_new:
        if item["id"] in existing_ids:
            continue
        data["items"].append(item)
        added += 1
    data["version"] = "v2.4"
    data["updated"] = "2026-05-17"
    data["source"] = (
        data.get("source", "")
        + " v2.4 — +60 items (20 bsl_code_v4 std, 20 wiki, 20 graph) for §4.1.9/10/11."
    )
    PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Appended {added}/{len(all_new)} new items; total now {len(data['items'])}")


if __name__ == "__main__":
    main()
