def register_resources_and_prompts(mcp_instance: Any) -> None:
    """Register all Resources and Prompts on a FastMCP instance."""

    # --- Resources ---

    @mcp_instance.resource("config://bsl-structure")
    def resource_bsl_structure() -> str:
        """Структура типов метаданных конфигурации 1С (JSON)"""
        return get_bsl_structure()

    @mcp_instance.resource("standards://coding-1c")
    def resource_coding_standards() -> str:
        """Стандарты кодирования 1С:Предприятие (Markdown)"""
        return get_coding_standards()

    @mcp_instance.resource("templates://module-skeleton")
    def resource_module_skeleton() -> str:
        """Шаблон BSL модуля со стандартными секциями"""
        return get_module_skeleton()

    # --- Prompts ---

    @mcp_instance.prompt("generate_handler")
    def prompt_generate_handler(object_type: str, object_name: str, event_name: str) -> str:
        """Сгенерировать обработчик события для объекта 1С"""
        return (
            f"Сгенерируй обработчик события '{event_name}' "
            f"для {object_type} '{object_name}' в 1С:Предприятие.\n\n"
            f"Требования:\n"
            f"1. Язык BSL, стандарты кодирования 1С\n"
            f"2. Комментарии с описанием параметров\n"
            f"3. Валидация входных данных\n"
            f"4. Обработка ошибок (Попытка-Исключение)\n"
            f"5. Регионы (#Область)\n"
            f"6. Логирование через ЖурналРегистрации\n"
        )

    @mcp_instance.prompt("refactor_module")
    def prompt_refactor_module(module_path: str, goal: str) -> str:
        """Рефакторинг BSL модуля"""
        return (
            f"Выполни рефакторинг BSL модуля '{module_path}'.\n\n"
            f"Цель: {goal}\n\n"
            f"Критерии:\n"
            f"- Разделение ответственности (SRP)\n"
            f"- Уменьшение цикломатической сложности\n"
            f"- DRY — выделение общих паттернов\n"
            f"- Оптимизация запросов к БД\n"
            f"- Документирование экспортных функций\n"
            f"- Регионы (#Область) для организации кода\n"
        )

    @mcp_instance.prompt("review_code")
    def prompt_review_code(code_snippet: str, review_focus: str) -> str:
        """Code review BSL кода"""
        return (
            f"Выполни review BSL кода с фокусом на '{review_focus}'.\n\n"
            f"```bsl\n{code_snippet}\n```\n\n"
            f"Проверь:\n"
            f"1. Безопасность (инъекции, права доступа)\n"
            f"2. Производительность (N+1, кэширование)\n"
            f"3. Стиль (именование, регионы)\n"
            f"4. Обработка ошибок\n"
            f"5. Читаемость\n\n"
            f"Выведи: список проблем, рекомендации, исправленный код.\n"
        )
