def get_coding_standards() -> str:
    """Returns 1C coding standards as markdown."""
    return """# Стандарты кодирования 1С:Предприятие

## Именование
- Переменные: `КоличествоЭлементов`, `ТекущийДокумент` (PascalCase, русский)
- Функции: `ПолучитьСуммуДокумента()`, `РассчитатьНалог()` (глагол + объект)
- Параметры: `ДокументСсылка`, `РежимПроведения` (описательное имя)

## Структура модуля
```
#Область ПеременныеМодуля
#Область ПубличныйАПИ          // Экспортные процедуры
#Область ОбработчикиСобытий     // ПриЗаписи, ПередЗаписью
#Область СлужебныеПроцедуры     // Внутренние функции
```

## Обработка ошибок
```bsl
Попытка
    РезультатОперации = ВыполнитьОперацию();
Исключение
    ЗаписьЖурналаРегистрации("Ошибка", УровеньЖурналаРегистрации.Ошибка,,, ОписаниеОшибки());
    ВызватьИсключение;
КонецПопытки;
```

## Запросы
- ВСЕГДА используйте параметры: `ГДЕ Ссылка = &Ссылка`
- Избегайте `ВЫБРАТЬ *` — перечисляйте нужные поля
- Используйте временные таблицы для сложных запросов
- Индексируйте временные таблицы: `ИНДЕКСИРОВАТЬ ПО Ссылка`

## Производительность
- Групповые операции вместо поэлементных циклов
- `СтрШаблон()` вместо конкатенации строк `+`
- Кэшируйте результаты повторяющихся вычислений
- Минимизируйте обращения к БД внутри циклов
"""


