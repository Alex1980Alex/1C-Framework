/**
 * Detects BSL module type from file path
 * @param filePath Path to BSL file
 * @returns Detected module type
 */
export function detectBSLModuleType(filePath: string): BSLModuleType {
  const lowerPath = filePath.toLowerCase();

  // Form modules (English and Russian)
  if (lowerPath.includes('/forms/') || lowerPath.includes('\\forms\\') ||
      lowerPath.includes('/формы/') || lowerPath.includes('\\формы\\')) {
    if (lowerPath.includes('/ext/form/module.bsl') || lowerPath.includes('\\ext\\form\\module.bsl')) {
      return BSLModuleType.FORM;
    }
  }

  // Object modules
  if (lowerPath.includes('/ext/objectmodule.bsl') || lowerPath.includes('\\ext\\objectmodule.bsl')) {
    return BSLModuleType.OBJECT;
  }

  // Manager modules
  if (lowerPath.includes('/ext/managermodule.bsl') || lowerPath.includes('\\ext\\managermodule.bsl')) {
    return BSLModuleType.MANAGER;
  }

  // Command modules (English and Russian)
  if (lowerPath.includes('/commands/') || lowerPath.includes('\\commands\\') ||
      lowerPath.includes('/команды/') || lowerPath.includes('\\команды\\')) {
    if (lowerPath.includes('/ext/commandmodule.bsl') || lowerPath.includes('\\ext\\commandmodule.bsl')) {
      return BSLModuleType.COMMAND;
    }
  }

  // Common modules (English and Russian)
  if (lowerPath.includes('/commonmodules/') || lowerPath.includes('\\commonmodules\\') ||
      lowerPath.includes('/общиемодули/') || lowerPath.includes('\\общиемодули\\')) {
    return BSLModuleType.COMMON;
  }

  // Session module
  if (lowerPath.includes('sessionmodule.bsl')) {
    return BSLModuleType.SESSION;
  }

  // Managed application module (check BEFORE ApplicationModule!)
  if (lowerPath.includes('managedapplicationmodule.bsl')) {
    return BSLModuleType.MANAGED_APPLICATION;
  }

  // Application module
  if (lowerPath.includes('applicationmodule.bsl')) {
    return BSLModuleType.APPLICATION;
  }

  // External connection module
  if (lowerPath.includes('externalconnectionmodule.bsl')) {
    return BSLModuleType.EXTERNAL_CONNECTION;
  }

  // RecordSet module
  if (lowerPath.includes('/ext/recordsetmodule.bsl') || lowerPath.includes('\\ext\\recordsetmodule.bsl')) {
    return BSLModuleType.RECORDSET;
  }

  // Value manager module
  if (lowerPath.includes('/ext/valuemanagermodule.bsl') || lowerPath.includes('\\ext\\valuemanagermodule.bsl')) {
    return BSLModuleType.VALUE_MANAGER;
  }

  return BSLModuleType.UNKNOWN;
}

/**
 * Gets context-aware prompt for BSL module
 * @param filePath Path to BSL file
 * @returns Context-specific prompt for the module type
 */
export function getBSLContextPrompt(filePath: string): string {
  const moduleType = detectBSLModuleType(filePath);
  return bslContextPrompts[moduleType];
}

