  private evaluateBSLSubsystemAnalysis(node: ThoughtNode): number {
    let score = 0;

    const thought = node.thought.toLowerCase();
    
    // Subsystem-specific terms
    const subsystemTerms = [
      'подсистема', 'иерархия', 'зависимость', 'интеграция',
      'безопасность', 'роль', 'поток данных', 'архитектура'
    ];
    
    for (const term of subsystemTerms) {
      if (thought.includes(term)) {
        score += 0.1;
      }
    }

    // Security and access terms
    const securityTerms = [
      'права доступа', 'роли', 'безопасность', 'аудит',
      'контроль', 'ограничения', 'защита'
    ];
    
    for (const term of securityTerms) {
      if (thought.includes(term)) {
        score += 0.15;
    }
    }

    // Integration terms
    const integrationTerms = [
      'веб-сервис', 'api', 'интеграция', 'обмен данными',
      'синхронизация', 'событие', 'очередь'
    ];
    
    for (const term of integrationTerms) {
      if (thought.includes(term)) {
        score += 0.15;
      }
    }

    // Architecture patterns
    const patternTerms = [
      'event-driven', 'microservices', 'api gateway', 'solid',
      'ddd', 'паттерн', 'архитектурный принцип'
    ];
    
    for (const term of patternTerms) {
      if (thought.includes(term)) {
        score += 0.2;
      }
    }

    // Strategic thinking bonus
    if (thought.includes('стратегия') || thought.includes('план') || thought.includes('рекомендации')) {
      score += 0.25;
    }

    return Math.min(score, 1.0);
  }

  private generateNodeId(): string {
    return `bsl-subsys-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`;
  }

  public async getMetrics(): Promise<BSLSubsystemMetrics> {
    const baseMetrics = await super.getMetrics();
    
    return {
      ...baseMetrics,
      name: 'BSL Subsystem Analyzer',
      subsystemsMapping: this.subsystemsMapping,
      crossSubsystemDependencies: this.crossSubsystemDependencies,
      securityViolations: this.securityViolations,
      integrationPoints: this.integrationPoints
    };
  }

  public async clear(): Promise<void> {
    this.subsystemsMapping = 0;
    this.crossSubsystemDependencies = 0;
    this.securityViolations = 0;
    this.integrationPoints = 0;
  }
